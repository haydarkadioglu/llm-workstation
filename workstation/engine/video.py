import base64
import inspect
import os
import tempfile
import time
from io import BytesIO
from typing import Callable, List, Optional

from PIL import Image

MAX_INPUT_EDGE = 704


class CancellationException(Exception):
    pass


def _fit_input_image(data_url: str) -> Image.Image:
    image = Image.open(BytesIO(base64.b64decode(data_url.split(",", 1)[-1]))).convert("RGB")
    w, h = image.size
    scale = min(MAX_INPUT_EDGE / max(w, h), 1.0)
    new_w = max(int(w * scale) // 16 * 16, 16)
    new_h = max(int(h * scale) // 16 * 16, 16)
    return image if (new_w, new_h) == (w, h) else image.resize((new_w, new_h), Image.Resampling.LANCZOS)


def _step_callback(pipeline, steps: int, on_progress, is_cancelled) -> dict:
    params = inspect.signature(pipeline.__call__).parameters

    def tick(step: int):
        if is_cancelled():
            raise CancellationException("Generation task aborted by user.")
        on_progress(step, steps)

    if "callback_on_step_end" in params:
        def on_step_end(pipe, step_index, timestep, callback_kwargs):
            tick(step_index + 1)
            return callback_kwargs

        return {"callback_on_step_end": on_step_end}
    if "callback" in params:
        return {"callback": lambda step, timestep, latents: tick(step + 1), "callback_steps": 1}
    return {}


def _as_uint8(frame):
    if hasattr(frame, "cpu"):
        frame = frame.cpu().numpy()
    return (frame * 255).astype("uint8") if frame.max() <= 1.0 else frame.astype("uint8")


def _to_pil_frames(frames) -> List[Image.Image]:
    if isinstance(frames, list) and frames and isinstance(frames[0], list):
        frames = frames[0]
    if hasattr(frames, "ndim"):
        if hasattr(frames, "cpu"):
            frames = frames.cpu().numpy()
        if frames.ndim == 5:
            frames = frames[0]
    return [f if isinstance(f, Image.Image) else Image.fromarray(_as_uint8(f)) for f in frames]


def _encode_mp4(frames, fps: int) -> str:
    import imageio.v2 as imageio
    import numpy as np

    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        path = os.path.join(tmp, "video.mp4")
        with imageio.get_writer(path, fps=fps, codec="libx264", macro_block_size=1) as writer:
            for frame in frames:
                writer.append_data(np.asarray(frame))
        with open(path, "rb") as handle:
            return base64.b64encode(handle.read()).decode("utf-8")


def generate_video(
    pipeline,
    prompt: str,
    negative_prompt: str,
    steps: int,
    frames: int,
    fps: int,
    image: Optional[str],
    on_progress: Callable[[int, int], None],
    is_cancelled: Callable[[], bool],
) -> str:
    import torch

    kwargs = {"prompt": prompt, "num_inference_steps": steps, "num_frames": frames}
    if negative_prompt:
        kwargs["negative_prompt"] = negative_prompt
    if torch.cuda.is_available():
        kwargs["generator"] = torch.Generator("cuda").manual_seed(int(time.time() * 1000) % 1000000)

    if image:
        params = inspect.signature(pipeline.__call__).parameters
        picture = _fit_input_image(image)
        key = "image" if "image" in params else "init_image" if "init_image" in params else None
        if key:
            kwargs[key] = picture
        else:
            print("[Video] Pipeline takes no input image, ignoring it.")
        if "width" in params:
            kwargs["width"], kwargs["height"] = picture.size

    kwargs.update(_step_callback(pipeline, steps, on_progress, is_cancelled))
    with torch.inference_mode():
        result = pipeline(**kwargs).frames

    pil_frames = _to_pil_frames(result)
    if not pil_frames:
        raise ValueError("No frames generated by the video model.")
    return _encode_mp4(pil_frames, fps)


def merge_videos(base64_videos: List[str], fps: int) -> str:
    import imageio.v2 as imageio

    frames = []
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        for index, video in enumerate(base64_videos):
            path = os.path.join(tmp, f"{index}.mp4")
            with open(path, "wb") as handle:
                handle.write(base64.b64decode(video.split(",", 1)[-1]))
            with imageio.get_reader(path, format="ffmpeg") as reader:
                for frame in reader:  # len(reader) is inf, so list() and extend() blow up
                    frames.append(frame)
    if not frames:
        raise ValueError("No video frames could be read for merging.")
    return _encode_mp4(frames, fps)
